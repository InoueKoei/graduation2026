// ============================================================
//  phrases.js — タイムアタックのお題
//
//  ロジックとは分けてあるので、ここだけ差し替えれば出題が変わる。
//
//  制約が2つある。
//   1. **ひらがなと「ー」だけ**。句読点キーを落としてあるので打てない（README 参照）
//   2. スペースも打てないので、分かち書きはしない
//
//  濁点・半濁点・小文字は SELECT で出せるので使ってよい。
//  打てない字が混じっていないかは、起動時に validatePhrases() が確かめる。
// ============================================================

/**
 * 足で踏むので、指で打つより1字が重い。長い文を並べると精神論になるので、
 * 6〜14字くらいの短い文にしてある。
 * 内容はこの作品そのもの（踏んで字を書く）についての言い回しで揃えた。
 */
export const PHRASES = Object.freeze([
  'あしのうらでもじをかく',
  'ふんでからきえるまで',
  'ゆかのうえのごじゅうおん',
  'おともなくふみかえる',
  'からだがぺんになる',
  'ひだりあしからはじめる',
  'まっすぐたつとかけない',
  'とびはねてだくてんをうつ',
  'ゆっくりふむとよくとどく',
  'いちもんじにあるく',
  'あしあとがもじになる',
  'かたあしでささえる',
  'ふみこむふかさでかわる',
  'おもたいじほどよくうごく',
  'こしをおとしてねらう',
  'とまってからかんがえる',
  'ゆびではなくあしでうつ',
  'いっぽずつすすむ',
]);

/**
 * 打てない字が混じっていないか確かめる。
 * お題を書き換えたときに気づけるよう、起動時に一度だけ走らせて console に出す。
 *
 * @param {(ch:string)=>boolean} canType その字を打てるか（toggle-core が答える）
 * @returns {Array<{phrase:string, chars:string[]}>} 打てない字を含むお題
 */
export function validatePhrases(canType) {
  const bad = [];
  for (const phrase of PHRASES) {
    const chars = [...phrase].filter((ch) => !canType(ch));
    if (chars.length) bad.push({ phrase, chars: [...new Set(chars)] });
  }
  return bad;
}
