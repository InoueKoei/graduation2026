// 絵文字の設定。ここだけ書き換えれば反応が変わる（操作画面と白い面を再読み込みする）。

// 読まれた語 → 流す絵文字。完全一致のときだけ流す。
// 1つの語に複数を並べると（['🐄', '🐮']）、流れる1粒ずつがその中から選ばれる。
// 語はひらがな・カタカナ・漢字・数字なんでもよい（Vision が返した文字列そのままで照合する）。
export const WORDS = {
  'うし': '🐄',
  'なし': '🍐',
  'なつ': '🌻',
  'あい': '❤️',
  'くり': '🌰',
  'よい': '👍',
};

export const FLOW = {
  SEC: 2.6,           // 流れている時間。このあいだカメラは見ない（絵文字を部品と取り違えないため）
  COOLDOWN_SEC: 8,    // 同じ語でまた流すまでの間
  COUNT: 28,          // 一度に流す粒の数
  SIZE_MIN: 0.035,    // 粒の大きさ（正方形の一辺に対する割合）
  SIZE_MAX: 0.075,
};

// 電光掲示板（操作画面の「電光掲示板のように流す」）の初期値。操作画面のスライダーで変えられる（そちらが優先）。
// 読まれた語を、絵文字の粒で書いた字にして、1字ずつ上から流す。字はフォントで描いて粒の並びにする。
// 粒は 1 マスずつ飛んで動く（電光掲示板の動き）
export const BOARD = {
  dots: 8,            // 1字の縦横の粒の数。少ないほど粗く、1粒が大きくなる
  char: 0.4,          // 1字の大きさ（正方形の一辺に対する割合）
  gap: 0.08,          // 字と字のあいだ
  speed: 0.55,        // 流れる速さ（正方形の一辺 / 秒）
  fill: 0.95,         // 粒（絵文字）の大きさ。1 マスに対する割合。1 より小さいと粒のあいだに隙間ができる
};

// 電光掲示板が流れきるまでの秒数。最初の字が上の端から入り、最後の字が下の端から出るまで。
// 操作画面はこのあいだカメラを止め、白い面はこのあいだ描く。同じ計算を両方で使う
export function boardSec(text, b = BOARD) {
  const n = [...new Intl.Segmenter('ja', { granularity: 'grapheme' }).segment(text)].length;
  return (1 + n * b.char + (n - 1) * b.gap) / b.speed;
}
