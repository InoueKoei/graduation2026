// 調整はぜんぶここで。
//
// ※ 距離にかかわる値は「px」ではなく「字面の大きさに対する比」で持つ。
//    px で固定すると、画面が小さくて字が小さいときに影響半径が字の半分を覆ってしまい、
//    まったく別の手触りになる。比で持てば、どの画面サイズでも同じ引き心地になる。

export const CONFIG = {
  // --- 文字 ---
  char: 'あ', // 最初に出す文字
  sizeRatio: 0.46, // 字面の大きさ（画面の短辺に対する比）
  sizeMax: 560, // 大きくなりすぎないための上限(px)

  // --- 輪郭の刻み ---
  // 節点の間隔（字面に対する比）。細かいほど滑らかだが節点が増えて重くなる。
  // 0.012 なら 400px の「あ」でおよそ 400 点。
  nodeSpacingEm: 0.012,

  // --- つまむ ---
  // ★ここが体験の要。掴んだ点から【輪郭に沿って】この長さぶんが一緒に動く。
  //   画面上の 2D 距離ではなく弧長で測るのが肝。2D で測ると「あ」の縦画を
  //   つまんだときに、すぐ隣を通る横棒まで巻き込まれ、字の一部がごっそり
  //   動いてしまう（＝つまむのではなく、ひきずる感触になる）。
  //   大きくすると長くゆるやかに、小さくすると鋭く尖って伸びる。
  grabArcEm: 0.22,
  // 1つのリングのうち、動かす輪郭の割合の上限。
  // カウンター（字の穴）は周長が短いので、弧長だけで決めると穴ごと
  // 引きずり出されて輪郭が交差する。割合でも抑える。
  grabArcMaxRingFraction: 0.22,
  grabToleranceEm: 0.1, // 輪郭からこの距離までは掴める。外すと空振り
  grabFalloff: 2.0, // 影響の落ち方。大きいほど中心付近だけが強く動く

  // 掴んだ点の「向かい側」（同じ線の反対の縁）を探す範囲。線幅の何倍まで見るか。
  // 向かい側も一緒に動かすことで線そのものが伸びる。これが無いと片側だけ動いて
  // 輪郭が自己交差し、破れたように見える。
  // 大きすぎると隣の線を向かい側と誤認するので 2 倍前後に留める。
  crossReach: 1.8,

  // 伸びの頭打ち（字面に対する比）。tanh を通すので、引くほど重くなり無限には伸びない。
  // 大きくすると字の外へ大きくはみ出し、伸びた部分が別の線と交差して破れやすくなる。
  maxStretchEm: 0.45,

  kGrab: 2600, // 掴んだ点が指へ追従する強さ
  cGrab: 74, // 追従の減衰。小さいと指の周りがぷるぷるする

  // --- ゴムの物理 ---
  kShape: 88, // 形状記憶。元の字形へ戻す力。大きいほど速く硬く戻る
  kEdge: 460, // 隣接ばね。輪郭の目を保ち、引きを滑らかに伝える
  damping: 6.2, // 速度の減衰(/s)。小さいほど、もどりが長く揺れる
  substeps: 4, // 1フレームあたりの積分回数。増やすと硬いばねでも安定する

  // --- その他 ---
  restEpsilon: 0.06, // これ以下の動きは「静止した」とみなして計算を休む(px)
};
