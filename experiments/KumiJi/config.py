# --- 撮影 -------------------------------------------------------------------
CAMERA_INDEX  = 0      # 起動後に `c` キーで切り替えられる（Continuity Camera 探し用）
# カメラの取り込み解像度。実機のカメラは 1920x1080 を出せるので、
# **投影面がフレームの一部しか占めないプロジェクター構成では上げる価値がある。**
# デジタルズームは画素を増やさないが、ここを上げるのは実際に増える。
# OCR に渡る画像が小さすぎるとき（実機で 120x138 まで痩せた）はまずここ。
FRAME_WIDTH   = 1280      # 投影面が小さく写るなら 1920 にする
FRAME_HEIGHT  = 720       #                        1080

# --- カメラのズーム率 -------------------------------------------------------
# プロジェクターだとカメラを離して置くことになり、投影面がフレームの一部しか
# 占めない。そのぶん部品の画素が減って OCR が読めなくなるので、寄せて撮る。
#
# ここでやるのは**切り出しだけで、拡大はしない**。引き伸ばすと画素が水増しに
# なるだけで、OCR に渡せる情報は増えないため。切り出した素の画素のまま扱い、
# 見た目はウィンドウ側の拡大表示でちゃんと寄る。
#   1.0 … フレーム全部を使う
#   2.0 … 縦横それぞれ半分の範囲だけを使う（面積で1/4に寄る）
CAM_ZOOM   = 1.0          # `z` `x` キーで増減
CAM_CENTER = (0.5, 0.5)   # 切り出す中心（正規化）。`h` `j` `k` `l` キーで動かす
CAM_ZOOM_STEP = 0.1
CAM_PAN_STEP  = 0.02

# レンズの光学ズームを先に試すか。効けばこちらの方が良い（画素が実際に増える）。
# ただし macOS の AVFoundation 経由では **まず効かない**。起動時に効いたか出す。
CAM_TRY_OPTICAL = False

# --- 二値化 -----------------------------------------------------------------
BLUR_KERNEL      = 5    # モアレ潰し。奇数のみ。液晶を撮ると縞が出るので必須
THRESHOLD_OFFSET = 0    # 閾値に足すオフセット。`-` `=` キーで増減
THRESHOLD_STEP   = 10   # `-` `=` の刻み。2 や 5 では 110 から 225 まで遠すぎた

# 部品は画面面積の数%しかないので、大津は「明るい側」に引っ張られて高く出る
# （実測で 183 になり、画面の明るさムラまで部品として拾った）。
# 部品は真っ黒・画面は真っ白とはっきり分かれているので、固定閾値の方が確実。
# 部品は地より**暗い**か、**明るい**か。
#   True  … 暗いものを部品とみなす（黒い部品／黒いペン。モニタ構成はこれ）
#   False … 明るいものを部品とみなす（白い部品を暗い地の上に置く）
#
# プロジェクター構成では、ここが逆になることがある。実機で 3Dプリントの部品を
# 白い紙に置いたとき **ink 210 / bg 243** しか離れなかった。差 33 は
# 「黒いものを撮った」値ではない。原因は2つのどちらか:
#   (a) 部品が明るい色で、白い紙との差がそもそも無い
#       → 暗い紙・暗い布の上に置いて DETECT_DARK = False にする
#   (b) 黒い部品が**プロジェクターの白い光で洗われている**
#       → CANVAS_BG = 0 にして置く場には何も投げない（下の注記を見る）
DETECT_DARK     = True

USE_OTSU        = False # `o` キーで切り替え
FIXED_THRESHOLD = 110   # これより暗い画素を部品とみなす
#
# ただしこれは**モニタの上に黒い部品を置いたとき**の値。
# 紙に投影して、紙にペンで書いたものを読ませる構成だと話が変わる。
# 紙は白飛びせず（実測 200 前後）、鉛筆やペンの線も真っ黒にはならない（150 前後）。
# 110 ではどちらも「明るい側」に入り、何も検出されない。
#
# 確認ウィンドウに ROI の明るさの分布を出してあるので、**それを見て決める**。
#   ink … 暗い方 1% の値。線がどれくらい暗いか
#   bg  … 中央値。地がどれくらい明るいか
# 閾値は ink と bg のあいだに置く。大津が選ぶ値も併記してあるので、
# 迷ったら `o` で大津に切り替えてしまうのが早い。

# --- 検出範囲（画面 ROI）----------------------------------------------------
# **元フレームの座標**で (x, y, w, h)。None なら起動時に自動検出する。
#
# プロジェクター構成では自動検出がまず当たらない（投影面がフレーム内で
# いちばん明るい塊にならない）。確認ウィンドウの上をドラッグすると決まって
# ターミナルに数値が出るので、**気に入った値をここに書いて固定する**。
# `W` キーでいまの値を書き戻せる。毎回囲い直さなくて済む。
#
# 狭くしすぎないこと。ここが小さいと OCR に渡る画像も小さくなり、Vision は
# テキスト行として拾わない（実機で 60x57 まで絞ってしまい何も読めなかった）。
# 目安として 300x300 以上、フレーム幅の 1/3 以上を確保する。
SCREEN_ROI = None

# --- 部品の抽出 -------------------------------------------------------------
# これ未満の連結成分はゴミとして捨てる。`[` `]` キーで増減。
# **画素数の絶対値なので、ROI の大きさに対して見ないと意味がない。**
# 実機で ROI を 80x82（=6560px）まで小さく囲ったとき、800 は ROI 面積の 12%
# だった。部品として通るのは 800〜1640px の狭い窓だけになり、閾値をどう
# 振っても 0個のまま。確認ウィンドウに ROI に対する比率を出してあるので、
# 8% を超えたら橙で警告する。目安は 1〜3%。
MIN_AREA       = 800
MAX_AREA_RATIO = 0.25  # ROI 面積のこの比率を超えるものは背景とみなして捨てる
DROP_BORDER    = True  # ROI の縁に接する塊を捨てる。画面の縁・ベゼルのノイズ対策
BORDER_PAD     = 2     # 縁とみなす余裕（画素）

# --- 表示 -------------------------------------------------------------------
CONTOUR_COLOR  = (0, 255, 0)      # 輪郭（緑）
CENTROID_COLOR = (0, 160, 255)    # 重心の十字（橙）
BOX_COLOR      = (255, 120, 0)    # 最小外接矩形（青）
HUD_COLOR      = (255, 255, 255)

# --- 判定のタイミング -------------------------------------------------------
# 流れはこの順。
#   1. 輪郭を検出する
#   2. 静止して STILL_SEC 秒たったら OCR にかける（1回だけ）
#   3. 読めなければ**何もしない**。光も出ない。動かせばまた試す
#   4. 読めたら、その合図として光が出て育ちはじめる
#   5. そのまま FIX_SECONDS 秒保持すると定着する
#
# 光は「そこに物がある」の合図ではなく「読めた」の合図。
# だから定着したものには必ず見出しがある。
AUTO_JUDGE = True      # `t` キーで手動（SPACE のみ）に切り替え
STILL_SEC  = 1.2       # 静止とみなすまでの秒数。ここで OCR が走る
POS_TOL    = 12        # 重心がこの画素数以内なら「動いていない」とみなす
REREAD_SEC = 0.0       # 読めなかったとき何秒後に再挑戦するか。0 で再挑戦しない

# 配置が変わったと認めるまでに、変化がこの秒数続く必要がある。
# 部品数は閾値や最小面積の際でちらつくので、1フレームの取りこぼしで
# 数え直すと、同じ配置を何度も読んで何度も定着させてしまう（実機で
# 同じ「より」が2枚定着した）。ここで吸収する。
MOVE_CONFIRM_SEC = 0.45

# 「全部どけた」と認めるまでに、部品が無い状態がこの秒数続く必要がある。
# どけたときは定着の抑止も絵文字のクールダウンも解ける——次は同じものでも
# 定着してよいし、反応も出してよい。**だから一瞬の 0 で解いてはいけない。**
# 実機で「なつ」が2枚定着し🌻が2回出た。読めずが連発するような検出のちらつき
# では部品数が一瞬 0 になり、そのたびに抑止が外れていた。
CLEAR_CONFIRM_SEC = 0.8

# 一度定着した配置は、これ以上ずらすまで再定着しない。
# 微調整で同じものが2枚3枚と定着するのを防ぐ（実機で同じ「なし」が2枚出た）。
# POS_TOL より十分大きく取る。小さくすると二重定着が戻る。
REFIX_TOL = 45

# 読みの確信度がこれ未満なら「読めなかった」とみなす。
# 0 で無効。誤読も記録に残したいので既定は 0 にしてある。
READ_MIN_CONF = 0.0

# 読みとして受ける文字の範囲。
#   "kana" … ひらがなだけ。**部屋の暗いものを拾って Vision が幻視した
#             ラテン文字（実機で「IAT8」「PAT8」が定着した）を落とせる**
#   "jp"   … かな＋カタカナ＋漢字
#   "any"  … 何でも受ける
#
# 誤読そのものは残したい（崩れた「ほ」が「ま」になるのはこの装置の見せ場）。
# ここで落としたいのは**そもそも部品を見ていない読み**の方。仮名を組む装置
# なので、仮名でない答えが返ったときは「置いたものを見ていない」と判断してよい。
READ_CHARSET = "kana"

# この字数未満の読みは捨てる。
#   1 … 何でも受ける（「つ」のような1部品の字も拾える）
#   2 … 2字以上だけ受ける。**組み立て途中の「な」「よ」を拾わなくなる**
# 実機ログでは1字の読みは確信度 0.30〜0.50 ばかりで、2字は 1.00 が多い。
# 途中が定着するのが邪魔なら 2 にする。
READ_MIN_CHARS = 1

# --- OCR に渡す切り出し -----------------------------------------------------
# 部品の外接矩形の何倍の余白を付けて切り出すか。1.0 なら縦横それぞれ3倍の画になる。
#
# ここは実測で決めた。Vision は「テキスト行」を探すので、**余白が足りないと
# そもそも文字として拾わない**。同じ字で比べた正解率:
#     pad=0.10 → 0/5      pad=0.60 → 5/5
#     pad=0.35 → 0/5      pad=1.00 → 5/5
#     （拡大してもむしろ悪化する。素の解像度のまま渡すのが良い）
# 0.35 がちょうど死んでいる帯だったので、1.0 を既定にしている。下げないこと。
OCR_PAD = 1.0

# --- 認識の対象 -------------------------------------------------------------
# いま部品があって物理的に組める字。probe での期待値の選択にだけ使う。
# 部品数の少ない順。1部品で成立する字があるのは想定内。
#   つ = 曲線1個 / う = つ + てん / い = 2部品 / は・ほ・よ = 3部品以上
BUILDABLE_CHARS = ["つ", "う", "い", "よ", "は", "ほ"]

# 機械が選ぶ先＝「規格の目録」。ひらがな46字すべて。
#
# ここを組める字だけに絞ってはいけない。6字しか候補がないと、何を置いても
# 6つのどれかになる＝「いちばん近い規格に丸める」ではなく「6択に丸める」に
# なってしまい、主張が成立しない。
#
# 46字あると、組めない字に落ちることが起きる（崩れた ほ が ま になる等）。
# それは事故ではなく情報で、この装置が見せたいものそのもの。
REFERENCE_CHARS = list(
    "あいうえおかきくけこさしすせそたちつてとなにぬねのはひふへほ"
    "まみむめもやゆよらりるれろわをん"
)

# =============================================================================
#  出力（main.py）── 「定着」
#
#  画面を2つに割る。
#
#    +--------------------------------+----------+
#    |                                | 定着の場   |
#    |      置く場（検出する範囲）        |          |
#    |      白地。明るい光しか描けない     | 痕跡が積まれる|
#    |                                | 何色でも可  |
#    +--------------------------------+----------+
#
#  置く場は検出の地なので、閾値より明るい色しか描けない（暗いと自分の描画を
#  部品として拾ってしまう）。だから「濃くしていく」には限界がある。
#  その限界があるからこそ、濃くなりきったものは**別の場所へ移して定着する**。
#  制約が形式を決めている。
# =============================================================================
CANVAS_W, CANVAS_H = 1920, 1080  # 寝かせたモニタの解像度に合わせる
CANVAS_BG   = 255                # 検出の地になるので白

# --- 写す範囲（プロジェクターの位置合わせ）----------------------------------
# プロジェクターは投影面のちょうどに収まってはくれない。台に対して大きすぎたり
# ずれていたりする。そこで**描いた画面を、この範囲の中へ収めてから出す**。
# 範囲の外は OUT_BG で塗る。プロジェクターは黒を「光を出さない」で表すので、
# 外側は何も映らない＝投影面だけを使える。
#
# 描画のコードは一切これを知らない。最後に一度だけ写し込むので、
# 位置合わせを何度やり直しても中身の作りには影響しない。
OUT_RECT = (0.0, 0.0, 1.0, 1.0)   # x, y, w, h（正規化）。`H J K L` で移動、`Z X` で拡縮
OUT_BG   = 0                      # 範囲の外の色。プロジェクターなら 0（＝映らない）

# 斜めから投げていて台形に歪むとき、4隅を直接指定して補正する。
# 左上・右上・右下・左下の順（正規化）。None なら OUT_RECT の矩形をそのまま使う。
#   例: ((0.06, 0.10), (0.94, 0.04), (0.97, 0.92), (0.03, 0.88))
#
# **まずプロジェクター本体の台形補正を使うこと。** こちらで歪めると、カメラ座標
# から画面座標への対応（roi_pt_to_canvas の線形近似）がそのぶん狂う。
# 本体で追い込めない残りを詰めるためのもの。
OUT_CORNERS = None

# 位置合わせ用の枠。`g` キーで出し入れする。
# 枠・4隅の鉤・中心の十字・目安の格子が出るので、これを見ながら
# プロジェクターの向きとレンズを合わせ、そのあと `H J K L` `Z X` で詰める。
#
# **枠を出しているあいだは検出を止める。**
# 置く場に描く色は本来 DRAW_MIN_LUMA より明るく保たないと自分の描画を部品と
# して拾ってしまうが、白地に対して明るい色では投影面で見えない（輝度差が
# 30 しか取れない）。位置合わせ中はまだ何も置いていないので、読むのをやめて
# しまえばよい。絵文字の反応中に検出を止めるのと同じ手で、こちらは
# 「機械が目を閉じているあいだに、こちらが枠を合わせる」。
OUT_GUIDE       = False
OUT_GUIDE_COLOR = (40, 110, 240)   # 検出を止めるので濃くてよい（見えることが先）
OUT_GUIDE_DIV   = 4                # 枠の中に引く格子の分割数

# -----------------------------------------------------------------------------
#  プロジェクターで使うときの注意（濃淡が反転する）
#
#  モニタは「明るい地に暗い字」を出せるが、**プロジェクターは光を足すことしか
#  できない**。黒を投げても投影面の色がそのまま見えるだけで、暗くはならない。
#
#  つまり定着の場の FIX_INK（暗いインク）は、プロジェクターでは**見えない**。
#  地と字を入れ替える必要がある。投影用の値はこれ:
#
#      FIX_INK       = (245, 245, 245)   # 光がインクになる
#      FIX_LABEL_INK = (150, 170, 190)
#      FIX_BG        = 0                 # 地は「投げない」＝投影面のまま
#      CANVAS_BG     = 255               # 置く場は投げ続ける（検出の地になる）
#
#  置く場についてはモニタ構成の直感が通らない。**照らすほど検出が悪くなる。**
#
#  モニタは下から光るので、置いたものは光を遮る影絵になった。だから 36 対 250 の
#  ような気持ちのよい差が出た。プロジェクターは上から照らすので、**紙も部品も
#  同じ光を浴びる**。黒い部品でも表面が光を返し、実機では ink 210 / bg 243、
#  差 33 まで潰れた。照明が検出の敵に回っている。
#
#      CANVAS_BG = 0     # 置く場には何も投げない。部屋の明かりで紙を見る
#
#  こうすると部品は自分の色の暗さで写り、差が戻る。プロジェクターの仕事は
#  出力だけになる。そして**光を足すことしかできないので、描いたものが部品として
#  拾われることが原理的にない**——モニタ構成でいちばん苦労した自己検出が、
#  ここでは消える。DRAW_MIN_LUMA を守る必要もなくなる。
#
#  副作用として auto_screen_roi（いちばん明るい塊を探す）は効かなくなる。
#  確認ウィンドウの上をドラッグして囲うこと。
# -----------------------------------------------------------------------------

# 画面の割り方（0〜1 の正規化。x, y, w, h）
PLACE_ZONE = (0.00, 0.00, 0.72, 1.00)   # 置く場。ここだけを検出する
FIX_ZONE   = (0.74, 0.00, 0.26, 1.00)   # 定着の場。検出しないので自由に描ける

# 輝度は cv2 のグレースケール換算 0.299R + 0.587G + 0.114B。
# 置く場に描く色は必ずこれ以上に保つこと。起動時に検査する。
DRAW_MIN_LUMA = 170

# --- 痕跡が濃くなっていく（置く場）------------------------------------------
FIX_SECONDS       = 3.0      # 手を止めてから定着しきるまでの秒数
FIX_RESET_ON_MOVE = True     # 動かしたら進行をやり直すか
HALO_COLOR        = (150, 200, 255)  # 濃くなりきったときの色（BGR）輝度 ≈ 210
HALO_RADIUS_START = 6        # 光の広がり 始め（画面座標の画素）
HALO_RADIUS_END   = 64       # 光の広がり 終わり
HALO_FALLOFF      = 1.6      # 濃さの落ち方。1=直線的、大きいほど物の際に寄る
HALO_SCALE_DIV    = 4        # 光の計算を 1/N 解像度で行う（速度のため）

# --- 定着した痕跡（定着の場）------------------------------------------------
# 形はあなたのまま残る。ただし、機械が読んだ字の見出しの下に収められる。
# 字体は一つずつ違うのに、分類だけが規格化される——1900年の仮名統一と同じ構造。
FIX_INK        = (40, 40, 40)   # 定着した痕跡の色（BGR）。ここは暗くてよい
FIX_LABEL_INK  = (130, 130, 130)
FIX_BG         = 248            # 定着の場の地の色
FIX_COLS       = 2              # 定着の場の列数
FIX_ROWS       = 6              # 行数。これを超えると古いものから消える
FIX_CELL_PAD   = 0.12           # 升の内側の余白（升の短辺に対する比）
FIX_SHOW_LABEL = True           # 読まれた字を見出しとして出すか
FIX_ORDER      = "rtl"          # 埋める順。"rtl"=右の列から（縦組みの読み）/ "ltr"

# --- 定着する瞬間 -----------------------------------------------------------
# 痕跡が置く場から定着の場へ移動する。移動中は置く場を横切るので、
# 暗い色では描けない（自己検出する）。だから **旅の途中は明るい光のまま、
# 到着した瞬間に色が乗る**。輝度の制約が、そのまま演出になっている。
FIX_TRAVEL_SEC  = 0.9    # 移動にかける秒数。0 で瞬間移動（演出なし）
FIX_TRAVEL_EASE = 2.2    # 動きの緩急。1=等速、大きいほど終盤が速い
FIX_RELEASE_SEC = 1.6    # 定着後、置く場の光が引くまでの秒数
# 読めなかったものは定着しないので、見出しなしの痕跡は原理的に出ない。

# =============================================================================
#  読めた語への反応（絵文字）
#
#  特定の語が読めたとき、絵文字が数秒だけ流れる。
